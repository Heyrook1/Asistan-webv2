/**
 * Escape untrusted values before interpolating them into HTML (e.g. email bodies).
 * Safe to use on the server (no DOM dependency).
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
